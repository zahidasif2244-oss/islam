/**
 * Generates one loader + one route per hadith book.
 *
 * Each generated module hard-codes the path of a single book file so Next's
 * file tracing bundles only that book into the function (4-44 MB instead of
 * 320 MB for all 17). Re-run with `node scripts/gen-hadith-routes.mjs` after
 * adding a new book to src/data/hadith + src/lib/constants.ts.
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const DATA_DIR = path.join(ROOT, 'src', 'data', 'hadith')
const LOADER_DIR = path.join(ROOT, 'src', 'lib', 'hadith-data')
const ROUTE_DIR = path.join(ROOT, 'src', 'app', 'api', 'hadith')

const books = fs
  .readdirSync(DATA_DIR)
  .filter(f => f.endsWith('.json'))
  .map(f => f.replace(/\.json$/, ''))

fs.mkdirSync(LOADER_DIR, { recursive: true })

for (const book of books) {
  const ident = book.replace(/[^a-z0-9_]/gi, '_')

  fs.writeFileSync(
    path.join(LOADER_DIR, `${ident}.ts`),
    `// AUTO-GENERATED by scripts/gen-hadith-routes.mjs — do not edit by hand.
import fs from 'fs'
import path from 'path'
import type { HadithBook } from '@/lib/hadith-handler'

let cache: HadithBook | null = null

export function load(): HadithBook | null {
  if (cache) return cache
  try {
    const file = path.join(process.cwd(), 'src', 'data', 'hadith', '${book}.json')
    cache = JSON.parse(fs.readFileSync(file, 'utf-8'))
    return cache
  } catch {
    return null
  }
}
`,
    'utf8'
  )

  const dir = path.join(ROUTE_DIR, ident)
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(
    path.join(dir, 'route.ts'),
    `// AUTO-GENERATED by scripts/gen-hadith-routes.mjs — do not edit by hand.
import { handleHadith } from '@/lib/hadith-handler'
import { load } from '@/lib/hadith-data/${ident}'

export const GET = (req: Request) => handleHadith(req, '${book}', load)
`,
    'utf8'
  )
}

console.log(`[hadith-routes] generated ${books.length} loaders + ${books.length} routes: ${books.join(', ')}`)
